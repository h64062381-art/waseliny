-- A small compatibility trigger keeps the old customer/payment names in sync.
create or replace function public.wasselni_sync_legacy_fields()
returns trigger language plpgsql as $$
begin
  if new.customer is null or new.customer = '' then new.customer := new.customer_name; end if;
  if new.customer_name is null or new.customer_name = '' then new.customer_name := coalesce(new.customer, ''); end if;
  if new.payment is null or new.payment = '' then new.payment := new.payment_method; end if;
  if new.payment_method is null or new.payment_method = '' then new.payment_method := new.payment; end if;
  return new;
end;
$$;

drop trigger if exists wasselni_sync_legacy_fields on public.orders;
create trigger wasselni_sync_legacy_fields
before insert or update on public.orders
for each row execute function public.wasselni_sync_legacy_fields();
